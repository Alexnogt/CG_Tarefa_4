# 9) Retroprojeção + fusão das vistas em nuvens de pontos no referencial do SfM
import open3d as o3d

def fuse(model, stride=2, rel_edge=0.03):
    acc = None
    for n, v in views_sel.items():
        d = ALIGNED[model][n]; H, W = d.shape
        valid = np.isfinite(d) & (d > 0) & (d < v["dmax"])
        d0 = np.where(valid, d, 0.0)
        gx = np.zeros_like(d0); gy = np.zeros_like(d0)
        gx[:, 1:] = np.abs(d0[:, 1:] - d0[:, :-1]) / np.maximum(d0[:, :-1], 1e-6)
        gy[1:, :] = np.abs(d0[1:, :] - d0[:-1, :]) / np.maximum(d0[:-1, :], 1e-6)
        valid &= ~((gx > rel_edge) | (gy > rel_edge))            # remove bordas de oclusão
        sm = np.zeros_like(valid); sm[::stride, ::stride] = True
        vs, us = np.nonzero(valid & sm)
        z = d[vs, us]; K = v["K"]
        Xc = np.stack([(us - K[0, 2]) * z / K[0, 0], (vs - K[1, 2]) * z / K[1, 1], z], 1)
        Xw = (Xc - v["t"]) @ v["R"]                              # câmera -> mundo
        pc = o3d.geometry.PointCloud()
        pc.points = o3d.utility.Vector3dVector(Xw)
        pc.colors = o3d.utility.Vector3dVector(IMGS[n][vs, us] / 255.0)
        pc = pc.voxel_down_sample(VOXEL * 0.5)
        pc.estimate_normals(o3d.geometry.KDTreeSearchParamHybrid(radius=VOXEL * 4, max_nn=30))
        pc.orient_normals_towards_camera_location(v["C"])        # normais voltadas p/ a câmera da vista
        acc = pc if acc is None else acc + pc
    acc = acc.voxel_down_sample(VOXEL); acc.normalize_normals()
    acc, _ = acc.remove_statistical_outlier(nb_neighbors=30, std_ratio=2.0)
    return acc.crop(o3d.geometry.AxisAlignedBoundingBox(BMIN, BMAX))   # corta o fundo

