# 7) Alinhamento e avaliação RMSE / MAE (protocolo afim-invariante, validação em pontos separados)
def robust_affine(x, y, iters=4, keep=0.8):
    A = np.stack([x, np.ones_like(x)], 1); idx = np.arange(len(x))
    for _ in range(iters):
        s, t = np.linalg.lstsq(A[idx], y[idx], rcond=None)[0]
        r = np.abs(A @ np.array([s, t]) - y)
        idx = np.argsort(r)[:max(3, int(keep * len(x)))]
    return s, t

def sample_at(arr, uv):
    H, W = arr.shape
    u = np.clip(np.round(uv[:, 0]).astype(int), 0, W-1); v = np.clip(np.round(uv[:, 1]).astype(int), 0, H-1)
    return arr[v, u]

def fit_affine(pred, kind, uv, z):
    x = sample_at(pred, uv); y = 1.0 / z if kind == "disparity" else z
    ok = np.isfinite(x) & np.isfinite(y)
    return robust_affine(x[ok], y[ok])

def fit_scale(pred, kind, uv, z):
    x = sample_at(pred, uv); y = 1.0 / z if kind == "disparity" else z
    ok = np.isfinite(x) & (x > 0) & np.isfinite(y)
    return float(np.median(y[ok] / x[ok]))

def to_depth(pred, kind, s, t=0.0):
    v = s * pred + t
    if kind == "disparity": return 1.0 / np.where(v > 1e-6, v, np.nan)
    return np.where(v > 1e-6, v, np.nan)

